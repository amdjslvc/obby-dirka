// ---- izbira jezika: shranjen > jezik brskalnika > angleščina ----
function detect() {
  try {
    const saved = localStorage.getItem('obby.lang')
    if (saved && D[saved]) return saved
  } catch {}
  for (const l of navigator.languages || [navigator.language]) {
    const code = String(l).slice(0, 2).toLowerCase()
    if (D[code]) return code
  }
  return 'en'
}

export let lang = detect()

export function setLang(l) {
  if (!D[l]) return
  lang = l
  try { localStorage.setItem('obby.lang', l) } catch {}
  applyDom()
}

// Prevod besedila; params zamenja {ime}
export function t(key, params = {}) {
  let s = D[lang][key] ?? D.en[key] ?? D.sl[key] ?? key
  for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, v)
  return s
}

export const blockName = (id) => (D[lang].b || D.en.b)[id - 1] || ''
export const emoteText = (i) => (D[lang].e || D.en.e)[i] || ''
export const hatName = (index) => (D[lang].h || D.en.h)[index] || ''

// Prevedi HTML: data-i18n (besedilo), data-i18n-html (z <b>), data-i18n-ph (placeholder), data-i18n-title
export function applyDom() {
  document.documentElement.lang = lang
  document.documentElement.dir = RTL.includes(lang) ? 'rtl' : 'ltr'
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n)
  for (const el of document.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml)
  for (const el of document.querySelectorAll('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh)
  for (const el of document.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle)
}
